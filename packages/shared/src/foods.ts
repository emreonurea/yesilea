export const FOODS: Food[] = ROWS.map(([name, c, kcal, protein_g, karb_g, yag_g, portions]) => ({
  name, category: FOOD_CATEGORIES[c], kcal, protein_g, karb_g, yag_g,
  portions: [...portions, ...(portions.some((p) => p.g === 100) ? [] : [{ label: "100 g", g: 100 }])],
}));

const INDEX = FOODS.map((f) => ({ f, n: normalize(f.name) }));

/** Türkçe karakterlere duyarsız arama; ada göre başlayanlar önce gelir. */
export function searchFoods(q: string, limit = 20): Food[] {
  const n = normalize(q);
  if (!n) return [];
  const words = n.split(" ");
  const hits = INDEX.filter(({ n: name }) => words.every((w) => name.split(" ").some((t) => t.startsWith(w)) || name.includes(w)));
  hits.sort((a, b) => Number(!b.n.startsWith(n)) - Number(!a.n.startsWith(n)) || a.n.length - b.n.length);
  return hits.slice(0, limit).map((h) => h.f);
}

/** Seçilen porsiyon ve adete göre besin değeri. */
export function foodNutrition(f: Food, grams: number) {
  const r = grams / 100;
  const round1 = (v: number) => Math.round(v * 10) / 10;
  return { kcal: Math.round(f.kcal * r), protein_g: round1(f.protein_g * r), karb_g: round1(f.karb_g * r), yag_g: round1(f.yag_g * r) };
}
